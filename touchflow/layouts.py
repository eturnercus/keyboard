def available_languages() -> dict[str, str]:
    """code -> native_name"""
    return {code: str(data["native_name"]) for code, data in LAYOUTS.items()}


def get_layout_rows(code: str) -> LayoutRows:
    data = LAYOUTS.get(code, LAYOUTS["en"])
    return data["rows"]  # type: ignore


def get_language_name(code: str) -> str:
    data = LAYOUTS.get(code)
    if data:
        return str(data["native_name"])
    return code.upper()
